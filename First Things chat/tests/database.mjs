import assert from 'node:assert/strict';
import { createSync, databaseSnapshot } from '../dist/database.js';
import { initial, addTask } from '../dist/model.js';
const tick = () => new Promise(resolve => setImmediate(resolve));
let finish;
const calls = [], statuses = [];
const sync = createSync(async value => {
  calls.push(value);
  if (calls.length === 1) await new Promise(resolve => { finish = resolve; });
}, (state, error) => statuses.push([state, error]));
sync.seed('{"tasks":[]}');
sync.push('{"tasks":[1]}');
sync.push('{"tasks":[1,2]}');
assert.equal(calls.length, 1);
assert.equal(sync.pending(), true);
finish();
await tick();
assert.deepEqual(calls, [{tasks:[1]}, {tasks:[1,2]}]);
assert.equal(sync.pending(), false);
assert.equal(statuses.at(-1)[0], 'saved');
sync.push('{"tasks":[1,2]}');
assert.equal(calls.length, 2);
let attempts = 0;
const failing = createSync(async () => { if (++attempts === 1) throw Error('Offline'); }, (phase, error) => statuses.push([phase, error]));
failing.push('{"tasks":[3]}');
await tick();
assert.equal(failing.pending(), true);
assert.deepEqual(statuses.at(-1), ['error', 'Offline']);
failing.push('{"tasks":[3,4]}');
assert.equal(attempts, 1);
failing.retry();
await tick();
assert.equal(attempts, 2);
assert.equal(failing.pending(), false);
const s = initial();
addTask(s, {title:'My task'});
s.messages = [{text:'Not stored'}];
assert.equal(JSON.parse(databaseSnapshot(s)).tasks[0].title, 'My task');
assert.equal(databaseSnapshot(s).includes('Not stored'), false);
console.log('PASS serialized saves, pending state, unchanged state, failed writes, retry, and snapshot fields');
