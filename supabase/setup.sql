-- Run in the Supabase SQL Editor. No DROP TABLE or deletion of existing data.
-- The four base tables follow the supplied ERD. Extra columns support ownership,
-- stable browser IDs, recurrence/preferences, and stale-tab protection.
begin;
create table if not exists public."user" (
  id bigint generated by default as identity primary key,
  phone_number text not null, date_created date default current_date, name text
);
create table if not exists public.goal (
  id bigint generated by default as identity primary key,
  user_id bigint not null references public."user"(id), goal_date date, goal_name text
);
create table if not exists public.task (
  id bigint generated by default as identity primary key,
  goal_id bigint not null references public.goal(id), task_name text,
  requires_photo boolean default false, is_completed boolean default false
);
create table if not exists public.daily (
  id bigint generated by default as identity primary key,
  user_id bigint not null references public."user"(id), list_date date,
  number_of_tasks integer, completed_task_num integer, breaks_available integer,
  breaks_used integer, apps_blocked boolean
);
alter table public."user" add column if not exists auth_user_id uuid references auth.users(id);
alter table public."user" add column if not exists data_version integer not null default 0;
alter table public.goal add column if not exists client_ref text;
alter table public.task add column if not exists client_ref text;
alter table public.task add column if not exists details jsonb not null default '{}'::jsonb;
alter table public.daily add column if not exists details jsonb not null default '{}'::jsonb;
update public.goal set client_ref = 'db-' || id where client_ref is null;
update public.task set client_ref = 'db-' || id where client_ref is null;
create unique index if not exists first_things_user_auth on public."user"(auth_user_id);
create unique index if not exists first_things_goal_ref on public.goal(user_id, client_ref);
create unique index if not exists first_things_daily_date on public.daily(user_id, list_date);

-- Browser access is through the two functions below, each scoped by auth.uid().
-- No public read/write policies and no need to disable RLS.
alter table public."user" enable row level security;
alter table public.goal enable row level security;
alter table public.task enable row level security;
alter table public.daily enable row level security;
revoke all on public."user", public.goal, public.task, public.daily from anon, authenticated;

create or replace function public.first_things_load()
returns jsonb language plpgsql security definer set search_path = '' as $$
declare owner_id bigint; revision integer; result jsonb;
begin
  if auth.uid() is null then raise exception 'Sign in before loading tasks'; end if;
  select id, data_version into owner_id, revision from public."user" where auth_user_id = auth.uid();
  if owner_id is null then return jsonb_build_object('version', 0, 'state', null); end if;
  select jsonb_build_object(
    'goals', coalesce((select jsonb_agg(jsonb_build_object(
      'id', coalesce(g.client_ref, 'db-' || g.id), 'title', g.goal_name, 'target', coalesce(g.goal_date::text, '')
    ) order by g.id) from public.goal g where g.user_id = owner_id and g.client_ref is distinct from '__inbox__'), '[]'::jsonb),
    'tasks', coalesce((select jsonb_agg(t.details || jsonb_build_object(
      'id', coalesce(t.client_ref, 'db-' || t.id), 'title', t.task_name,
      'goalId', case when g.client_ref = '__inbox__' then '' else coalesce(g.client_ref, 'db-' || g.id) end,
      'photo', coalesce(t.requires_photo, false), 'done', coalesce(t.is_completed, false)
    ) order by t.id) from public.task t join public.goal g on g.id = t.goal_id where g.user_id = owner_id), '[]'::jsonb),
    'daily', coalesce((select d.details from public.daily d where d.user_id = owner_id order by d.id desc limit 1), '{}'::jsonb)
  ) into result;
  return jsonb_build_object('version', revision, 'state', result);
end $$;

create or replace function public.first_things_save(payload jsonb, expected_version integer)
returns integer language plpgsql security definer set search_path = '' as $$
declare
  owner_id bigint; revision integer; goal_row jsonb; task_row jsonb;
  parent_id bigint; inbox_id bigint; task_id bigint; daily_data jsonb;
  completed integer; remaining integer; used_breaks integer; available_breaks integer;
begin
  if auth.uid() is null then raise exception 'Sign in before saving tasks'; end if;
  if jsonb_typeof(payload->'tasks') is distinct from 'array' or
     jsonb_typeof(payload->'goals') is distinct from 'array' then
    raise exception 'Tasks and goals must be arrays';
  end if;
  insert into public."user"(auth_user_id, name, phone_number)
    values(auth.uid(), payload->'profile'->>'name', payload->'profile'->>'phone')
    on conflict(auth_user_id) do nothing;
  -- A row lock serializes saves; the version prevents stale tabs overwriting data.
  select id, data_version into owner_id, revision from public."user"
    where auth_user_id = auth.uid() for update;
  if revision <> expected_version then
    raise exception 'Data changed in another tab. Reload to load the latest saved tasks before editing.';
  end if;
  update public."user" set name = payload->'profile'->>'name',
    phone_number = payload->'profile'->>'phone', data_version = revision + 1 where id = owner_id;
  -- Tasks without a visible goal still need the ERD task → goal → user relationship.
  insert into public.goal(user_id, client_ref, goal_name)
    values(owner_id, '__inbox__', 'Unassigned tasks') on conflict(user_id, client_ref) do nothing;
  select id into inbox_id from public.goal where user_id = owner_id and client_ref = '__inbox__';
  for goal_row in select value from jsonb_array_elements(payload->'goals') loop
    if coalesce(goal_row->>'id', '') in ('', '__inbox__') then raise exception 'Invalid goal ID'; end if;
    insert into public.goal(user_id, client_ref, goal_name, goal_date)
      values(owner_id, goal_row->>'id', goal_row->>'title', nullif(goal_row->>'target', '')::date)
      on conflict(user_id, client_ref) do update set goal_name = excluded.goal_name, goal_date = excluded.goal_date;
  end loop;
  for task_row in select value from jsonb_array_elements(payload->'tasks') loop
    if coalesce(task_row->>'id', '') = '' or trim(coalesce(task_row->>'title', '')) = '' then
      raise exception 'Tasks need an ID and a title';
    end if;
    parent_id := inbox_id;
    if coalesce(task_row->>'goalId', '') <> '' then
      select id into parent_id from public.goal where user_id = owner_id and client_ref = task_row->>'goalId';
      if parent_id is null then raise exception 'Task goal does not belong to this user'; end if;
    end if;
    select t.id into task_id from public.task t join public.goal g on g.id = t.goal_id
      where g.user_id = owner_id and coalesce(t.client_ref, 'db-' || t.id) = task_row->>'id';
    if task_id is null then
      insert into public.task(goal_id, client_ref, task_name, requires_photo, is_completed, details)
        values(parent_id, task_row->>'id', task_row->>'title', (task_row->>'photo')::boolean,
          (task_row->>'done')::boolean, task_row - array['id','title','goalId','photo','done']);
    else
      update public.task set goal_id = parent_id, client_ref = task_row->>'id', task_name = task_row->>'title',
        requires_photo = (task_row->>'photo')::boolean, is_completed = (task_row->>'done')::boolean,
        details = task_row - array['id','title','goalId','photo','done'] where id = task_id;
    end if;
  end loop;
  -- Removing a UI task removes only the corresponding task owned by this user.
  delete from public.task t using public.goal g where t.goal_id = g.id and g.user_id = owner_id
    and not exists(select 1 from jsonb_array_elements(payload->'tasks') x where x->>'id' = coalesce(t.client_ref, 'db-' || t.id));
  delete from public.goal g where g.user_id = owner_id and g.client_ref is distinct from '__inbox__'
    and not exists(select 1 from jsonb_array_elements(payload->'goals') x where x->>'id' = coalesce(g.client_ref, 'db-' || g.id));
  daily_data := payload->'daily';
  select count(*) into completed from jsonb_array_elements(payload->'tasks') x where (x->>'done')::boolean;
  remaining := jsonb_array_length(payload->'tasks') - completed;
  select count(*) filter(where (value->>'used')::boolean), count(*) filter(where not (value->>'used')::boolean)
    into used_breaks, available_breaks from jsonb_each(coalesce(daily_data->'ledger', '{}'::jsonb));
  insert into public.daily(user_id, list_date, number_of_tasks, completed_task_num, breaks_available, breaks_used, apps_blocked, details)
    values(owner_id, (daily_data->>'day')::date, jsonb_array_length(payload->'tasks'), completed, available_breaks, used_breaks,
      remaining > 0 and jsonb_array_length(daily_data->'selectedApps') > 0 and
        coalesce((daily_data->>'activeUntil')::numeric, 0) <= extract(epoch from now()) * 1000 + coalesce((daily_data->>'timeOffset')::numeric, 0), daily_data)
    on conflict(user_id, list_date) do update set number_of_tasks = excluded.number_of_tasks,
      completed_task_num = excluded.completed_task_num, breaks_available = excluded.breaks_available,
      breaks_used = excluded.breaks_used, apps_blocked = excluded.apps_blocked, details = excluded.details;
  return revision + 1;
end $$;
revoke all on function public.first_things_load() from public, anon;
revoke all on function public.first_things_save(jsonb, integer) from public, anon;
grant execute on function public.first_things_load() to authenticated;
grant execute on function public.first_things_save(jsonb, integer) to authenticated;
commit;
